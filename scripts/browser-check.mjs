import {writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const page = await fetch('http://127.0.0.1:9222/json/new?http://127.0.0.1:4173/',{method:'PUT'}).then(r=>r.json());
const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise(resolve=>socket.addEventListener('open',resolve,{once:true}));
let id=0; const pending=new Map(); const errors=[];
socket.addEventListener('message',event=>{const m=JSON.parse(event.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result);}if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.text);});
const send=(method,params={})=>new Promise((resolve,reject)=>{const key=++id;pending.set(key,{resolve,reject});socket.send(JSON.stringify({id:key,method,params}));});
const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
const waitFor=async expression=>{for(let i=0;i<80;i++){if(await evaluate(expression))return;await new Promise(r=>setTimeout(r,100));}throw new Error('Timed out: '+expression);};
await send('Runtime.enable');await send('Page.enable');await send('Page.bringToFront');
await evaluate('localStorage.removeItem("firststep.saved.v1")');await send('Page.reload');
await waitFor('document.querySelectorAll(".card").length===5');
const report=[];
for(const [name,width,height] of [['desktop',1440,1100],['tablet',768,1100],['mobile',360,900]]){
 await send('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false});
 await evaluate('document.fonts.ready');
 assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'),true,`${name}: horizontal overflow`);
 const shot=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:true});
 await writeFile(`docs/screenshots/${name}.png`,Buffer.from(shot.data,'base64'));
 report.push(`${width}px: no horizontal overflow; screenshot captured`);
}
await evaluate('document.querySelector("#search").value="  SQL  "; document.querySelector("#search").dispatchEvent(new Event("input"))');
assert.equal(await evaluate('document.querySelectorAll(".card").length'),2);
await evaluate('document.querySelector("#mode").value="Hybrid";document.querySelector("#mode").dispatchEvent(new Event("change"))');
assert.equal(await evaluate('document.querySelectorAll(".card").length'),1);
await evaluate('document.querySelector("#clear").click();document.querySelector("#search").value="no-match";document.querySelector("#search").dispatchEvent(new Event("input"))');
assert.equal(await evaluate('!document.querySelector("#state").hidden'),true);
await evaluate('document.querySelector("#clear").click();document.querySelector("[data-save]").click();document.querySelector("#saved-nav").click()');
assert.equal(await evaluate('document.querySelectorAll(".card").length'),1);
await send('Page.reload');await waitFor('document.querySelectorAll(".card").length===5');
assert.equal(await evaluate('document.querySelector("#saved-count").textContent'),'1');
await evaluate('document.querySelector("[data-details]").click()');
assert.equal(await evaluate('document.querySelector("#details").open && document.activeElement.id==="close-dialog"'),true);
await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
await waitFor('!document.querySelector("#details").open && document.activeElement.hasAttribute("data-details")');
await send('Network.enable'); await send('Network.setBlockedURLs',{urls:['*internships.json*']});
await send('Page.reload');await waitFor('document.querySelector("#result-count").textContent==="Opportunities unavailable"');
await send('Network.setBlockedURLs',{urls:[]});await evaluate('document.querySelector("#state button").click()');
await waitFor('document.querySelectorAll(".card").length===5');
assert.deepEqual(errors,[]);
report.push('PASS: search, combined filters, empty state, saves across reload, dialog focus, Escape and focus return, failed fetch and retry, no JavaScript runtime exceptions');
await writeFile('docs/browser-results.txt',report.join('\n')+'\n');
console.log(report.join('\n'));socket.close();
